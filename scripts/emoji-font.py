"""Build the bundled emoji font: only the emoji the app uses, from Noto Color Emoji (COLRv1, SIL OFL 1.1).

Why: phones draw emoji with their own font, so the same word looks different on Samsung, Xiaomi
or an old Android (some show empty boxes). Chrome 108+ and Firefox draw this font instead;
other browsers (Safari) ignore it and keep their own emoji (see the tech() hint in the CSS).

Run after adding new emoji to the content (needs `pip install fonttools brotli` and the
Noto COLRv1 font as one file, e.g. DiphylleiaEmoji-COLRv1.woff2 from the npm package @diphylleia/emoji):
    node scripts/emoji-list.mjs > /tmp/emoji.txt
    python3 scripts/emoji-font.py /path/to/DiphylleiaEmoji-COLRv1.woff2 /tmp/emoji.txt
Writes public/fonts/bix-emoji.woff2, src/styles/emoji-font.css and scripts/emoji-font-codepoints.txt.
"""
import os, sys
from fontTools.ttLib import TTFont
from fontTools import subset

src_font, list_file = sys.argv[1], sys.argv[2]
root = os.path.join(os.path.dirname(__file__), '..')
out_dir = os.path.join(root, 'public', 'fonts')
os.makedirs(out_dir, exist_ok=True)
want = {int(x, 16) for x in open(list_file).read().split()}
font = TTFont(src_font)
cmap = set(font.getBestCmap())
missing = sorted(want - cmap)
keep = want & cmap
opts = subset.Options()
opts.flavor = 'woff2'
opts.layout_features = ['*']  # ZWJ sequences (family, teacher…), skin tones, keycaps
opts.name_IDs = ['*']
opts.notdef_outline = False
sub = subset.Subsetter(opts)
sub.populate(unicodes=keep)
sub.subset(font)
font.flavor = 'woff2'
out = os.path.join(out_dir, 'bix-emoji.woff2')
font.save(out)

# digits stay with the text font, so keycaps like 6️⃣ use the phone's own emoji (old ones, every phone has them)
def ranges(cps):
    out, run = [], []
    for c in sorted(cps):
        if run and c == run[-1] + 1:
            run.append(c)
        else:
            if run: out.append(run)
            run = [c]
    if run: out.append(run)
    return ','.join(f'U+{r[0]:x}' if len(r) == 1 else f'U+{r[0]:x}-{r[-1]:x}' for r in out)

css = f"""/* Generated by scripts/emoji-font.py: the emoji this app uses, from Noto Color Emoji (SIL OFL 1.1, Google). */
/* tech(color-COLRv1): only browsers that can draw it use it (Chrome 108+, Firefox); others keep their own emoji. */
@font-face {{
  font-family: 'Bix Emoji';
  font-display: swap;
  src: url('/fonts/bix-emoji.woff2') format('woff2') tech(color-COLRv1);
  unicode-range: {ranges(c for c in keep if c >= 0x80)};
}}
"""
open(os.path.join(root, 'src', 'styles', 'emoji-font.css'), 'w').write(css)
# the same list for the unit test (tests/emoji-font.test.ts)
open(os.path.join(root, 'scripts', 'emoji-font-codepoints.txt'), 'w').write('\n'.join(f'{c:x}' for c in sorted(keep)) + '\n')
print(f'{os.path.getsize(out) // 1024} KB, {len(keep)} code points; not in the font: {[hex(c) for c in missing]}')
